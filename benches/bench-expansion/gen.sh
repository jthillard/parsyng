#!/usr/bin/env bash
# Regenerates src/generated.rs: N types cycling through the shapes every
# `HeapSize` implementation in `bench-comptime` supports.
set -euo pipefail
N=${1:-200}
cd "$(dirname "$0")"
{
    echo "// @generated by gen.sh — do not edit."
    for ((i = 0; i < N; i++)); do
        case $((i % 4)) in
        0) cat <<RS
/// Named fields.
#[derive(HeapSize)]
pub struct Named$i {
    pub id: u64,
    pub name: String,
    pub(crate) tags: Vec<String>,
    #[allow(dead_code)]
    pub parent: Option<Box<Named$i>>,
    pub scores: Vec<Option<u32>>,
    pub flag: u8,
}
RS
        ;;
        1) cat <<RS
/// Tuple fields.
#[derive(HeapSize)]
pub struct Tuple$i(pub String, pub Vec<u8>, u32, pub Option<String>);
RS
        ;;
        2) cat <<RS
/// Lifetime, type and const generics.
#[derive(HeapSize)]
pub struct Generic$i<'a, T: Clone, U, const N: usize> {
    pub name: &'a str,
    pub value: T,
    pub values: Vec<U>,
    pub array: [u8; N],
}
RS
        ;;
        3) cat <<RS
/// Unit struct.
#[derive(HeapSize)]
pub struct Unit$i;
RS
        ;;
        esac
    done
} > src/generated.rs
