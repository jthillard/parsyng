//! Prints the items of every fixture file that syn, parsyng and moxy all
//! parse (see `common_subset`), wrapped in `bench_comptime::parse_bench!`.
//! Used by `benches/bench-parse/gen.sh`.

fn main() {
    println!("// @generated by gen.sh — do not edit.");
    println!("bench_comptime::parse_bench! {{");
    for (name, src) in parsyng_bench_runtime::FILES {
        println!("// {name}");
        println!("{}", parsyng_bench_runtime::common_subset(src));
    }
    println!("}}");
}
